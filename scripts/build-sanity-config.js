// Regenerates js/sanity-config.js from SANITY_PROJECT_ID / SANITY_DATASET env vars
// when they are set (e.g. on Netlify). If no project id is set, the committed
// placeholder is left untouched so the site keeps using hardcoded fallback content.
'use strict';
const fs = require('fs');
const path = require('path');

const projectId = (process.env.SANITY_PROJECT_ID || '').trim();
const dataset = (process.env.SANITY_DATASET || 'production').trim();
const out = path.join(__dirname, '..', 'js', 'sanity-config.js');

if (!projectId) {
  console.log('[sanity-config] SANITY_PROJECT_ID not set - keeping placeholder (fallback content active)');
  process.exit(0);
}

const content =
  `/* Auto-generated by scripts/build-sanity-config.js from env vars. Do not edit by hand. */\n` +
  `window.GREATSCOPE_SANITY = { projectId: ${JSON.stringify(projectId)}, dataset: ${JSON.stringify(dataset)} };\n`;

fs.writeFileSync(out, content);
console.log(`[sanity-config] wrote projectId=${projectId} dataset=${dataset}`);
